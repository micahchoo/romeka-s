#!/usr/bin/env python3
"""Render `docs/api.md` from the tables in `model.py`."""

from __future__ import annotations

from markdown import code, table
from model import (
    OPERATION_NAMES,
    Doc,
    adapter_write_rows,
    error_status_codes,
    error_status_rows,
    list_parameters,
    property_row_fields,
    read_access_rows,
    request_body_rows,
)
from wire import WireItem


def render_document(doc: Doc) -> str:
    out: list[str] = [
        "# The `/api` reference",
        "",
        "Audience: a developer integrating against the HTTP API. Romeka S keeps Omeka S's `/api` "
        "surface, so a client written for Omeka S works unchanged.",
        "",
        "Generated by `docs/gen.sh` from the `omeka-api` source. Do not edit by hand: change the "
        "source, run `cd docs && ./gen.sh`, and commit both the source change and this file. "
        "`./gen.sh --check` fails when this file is stale.",
        "",
        "## What this document is generated from",
        "",
    ]
    sources_section(out)
    requests_section(out)
    responses_section(out)
    routes_section(out, doc)
    access_section(out)
    resources_section(out, doc)
    shared_section(out, doc)
    errors_section(out)
    return "\n".join(out).rstrip("\n") + "\n"


def sources_section(out: list[str]) -> None:
    out.append(
        table(
            ["Source file", "What is read from it"],
            [
                [
                    "`crates/omeka-api/src/routes.rs`",
                    "the path templates, the allowed methods per shape, and the method to "
                    "adapter-operation mapping",
                ],
                [
                    "`crates/omeka-api/src/adapters/*.rs`",
                    "one registration per adapter: its resource name, its representation, and the "
                    "operations it implements",
                ],
                [
                    "`crates/omeka-api/src/wire/*.rs`",
                    "the response document members, their JSON keys and their optionality",
                ],
                [
                    "`crates/omeka-api/src/read/*.rs`",
                    "the list parameters each search handler reads, and which resource each handler "
                    "serves",
                ],
                [
                    "`crates/omeka-api/src/write/*.rs`",
                    "the request body members each create and update handler reads",
                ],
            ],
        )
    )
    out.append("")


def requests_section(out: list[str]) -> None:
    out.append("## Requests")
    out.append("")
    out.append(
        "Every `/api` request takes the API key as two query parameters, `key_identity` and "
        "`key_credential` (`crates/omeka-api/src/auth.rs`). With neither, the request is anonymous."
    )
    out.append("")
    out.append(
        "A write (POST, PUT, PATCH) must send `Content-Type: application/json` or "
        "`multipart/form-data`; anything else is 415. A GET and a DELETE need no content type."
    )
    out.append("")
    row_fields = property_row_fields()
    if row_fields:
        out.append(
            "A `property` row carries "
            + ", ".join(code(field) for field in row_fields)
            + " (`crates/omeka-api/src/read/query.rs`); a row with no usable value is dropped."
        )
        out.append("")


def responses_section(out: list[str]) -> None:
    out.append("## Responses")
    out.append("")
    out.append(
        table(
            ["Header", "Value", "Where it is set"],
            [
                [
                    "`Content-Type`",
                    "`application/ld+json`",
                    "`crates/omeka-api/src/read/response.rs`",
                ],
                ["`Omeka-S-Version`", "`4.3.0-alpha`", "`crates/omeka-api/src/read/response.rs`"],
                [
                    "`Omeka-S-Total-Results`",
                    "the row count before pagination, on a listing",
                    "`crates/omeka-api/src/read/response.rs`",
                ],
                [
                    "`Link`",
                    '`rel="next"`, `rel="prev"`, `rel="first"`, `rel="last"` on a listing',
                    "`crates/omeka-api/src/read/response.rs`",
                ],
            ],
        )
    )
    out.append("")
    out.append("A search answers a bare JSON array. A member read answers one object.")
    out.append("")


def routes_section(out: list[str], doc: Doc) -> None:
    out.append("## Routes")
    out.append("")
    out.append(
        "One row per (resource, path, method) in `crates/omeka-api/src/routes.rs`. The handler "
        "column says who serves the route: the server, or an error because the server or the adapter "
        "has no operation for it. A served route can still answer 403 for a caller without the "
        "permission, 404 for a missing row, and 405 for a method the path shape does not route."
    )
    out.append("")
    out.append(table(["Resource", "Method", "Path", "Operation", "Handler"], doc.rows))
    out.append("")
    out.append(
        "Writes to a resource with no write handler answer 501, even where the adapter does not "
        "list the operation; the write dispatch never consults the operation list, where the read "
        "dispatch does (`crates/omeka-api/src/write/mod.rs`, "
        "`crates/omeka-api/src/read/mod.rs`)."
    )
    out.append("")
    consts = doc.consts
    allow = doc.allow
    out.append(
        "Allowed methods per shape: "
        f"`{consts['COLLECTION_PATH']}` "
        f"{', '.join(allow['COLLECTION_ALLOW'])}, "
        f"`{consts['MEMBER_PATH']}` "
        f"{', '.join(allow['MEMBER_ALLOW'])}, "
        f"`{consts['CONTEXT_PATH']}` and the root "
        f"{', '.join(allow['ROOT_ALLOW'])}. Any other method is 405 with an `Allow` header."
    )
    out.append("")


def access_section(out: list[str]) -> None:
    out.append("## Access")
    out.append("")
    out.append("Search and read (`Api::allow` in `crates/omeka-api/src/read/mod.rs`).")
    out.append("")
    out.append(table(["Resources", "Allowed caller"], read_access_rows()))
    out.append("")
    out.append(
        "Create, update and delete (`write::access::adapter` in "
        "`crates/omeka-api/src/write/access.rs`). One row per resource and one grant per "
        "operation. The admin roles pass every row, so a cell lists the other roles that row "
        "admits, and a resource with no row is admin-only. A resource with no write handler "
        "passes this check and reaches the 501 the route table marks."
    )
    out.append("")
    out.append(table(["Resource", "Create", "Update", "Delete"], adapter_write_rows()))
    out.append("")
    out.append(
        "Delete then checks the entity rule: `write::access::resource_entity` for items, item sets, "
        "media and assets (an editor or an admin role may remove any row, an author or a reviewer "
        "only a row they own), `owned_entity` for sites and site pages (an admin role any row, "
        "everyone else only their own, so an anonymous caller is refused), `user_entity` for users "
        "(an admin may not remove their own account, and a site admin may not remove another "
        "admin), and `vocabulary_entity` for vocabularies (a global admin any row, a site admin "
        "only one they added). Update carries `resource_entity_update`: a reviewer and up may "
        "change any row of items, item sets, media, assets and resource templates, and an author "
        "only a row they own."
    )
    out.append("")


def resources_section(out: list[str], doc: Doc) -> None:
    out.append("## Resources")
    out.append("")
    for adapter in doc.adapters:
        resource_section(out, doc, adapter)


def resource_section(out: list[str], doc: Doc, adapter: dict[str, object]) -> None:
    resource = str(adapter["name"])
    out.append(f"### `{resource}`")
    out.append("")
    out.append(
        f"{adapter['representation']}, registered by "
        f"`crates/omeka-api/src/adapters/{adapter['module']}.rs`. "
        "Implemented operations in the registry: "
        + ", ".join(OPERATION_NAMES.get(op, op.lower()) for op in adapter["operations"])
        + "."
    )
    out.append("")
    out.append(
        table(
            ["Method", "Path", "Operation", "Handler"],
            [[row[1], row[2], row[3], row[4]] for row in doc.rows if row[0] == resource],
        )
    )
    out.append("")
    params = list_parameters(resource, doc.search_fn, doc.index)
    if params:
        collection = doc.consts["COLLECTION_PATH"].replace("{resource}", resource)
        out.append(f"List parameters (`GET {collection}`).")
        out.append("")
        out.append(table(["Parameter", "Kind", "Read by"], params))
        out.append("")
    body_rows = request_body_rows(resource, doc.write_dispatch)
    if body_rows:
        out.append("Request body members (`POST` and `PUT`).")
        out.append("")
        out.append(table(["Member", "Kind", "Read by"], body_rows))
        out.append("")
    wire_file = doc.wire_by_resource.get(resource)
    if not wire_file:
        out.append(
            "No response document of its own: the adapter delegates to the target resource."
        )
        out.append("")
        return
    for item in doc.wire_by_file[wire_file]["items"]:
        wire_item_section(
            out, item, f"Response members of `{item.name}` (`crates/omeka-api/src/wire/{wire_file}`)."
        )


def wire_item_section(out: list[str], item: WireItem, heading: str) -> None:
    out.append(heading)
    out.append("")
    if item.doc:
        out.append(item.doc)
        out.append("")
    if item.members:
        out.append(
            table(
                ["JSON key", "Rust field", "Type", "Notes"],
                [
                    [
                        code(member.key) if member.key != "(flattened)" else "(flattened)",
                        code(member.name),
                        code(member.type),
                        member.note(),
                    ]
                    for member in item.members
                ],
            )
        )
    elif item.variants:
        out.append(
            table(
                ["Variant", "Wire value", "Payload"],
                [
                    [code(variant), code(rename) if rename else "", code(payload)]
                    for variant, rename, payload in item.variants
                ],
            )
        )
    elif item.inner is not None:
        out.append(f"Its value is {code(item.inner)}.")
    out.append("")


def shared_section(out: list[str], doc: Doc) -> None:
    out.append("## Shared wire shapes")
    out.append("")
    out.append(
        "Every document above refers to these, all defined in "
        "`crates/omeka-api/src/wire/common.rs`."
    )
    out.append("")
    for item in doc.wire_by_file["common.rs"]["items"]:
        wire_item_section(out, item, f"### `{item.name}`")


def errors_section(out: list[str]) -> None:
    out.append("## Errors")
    out.append("")
    out.append(
        'An error body is `{"errors": {"<field>": "<message>"}}`, or a list of messages for one '
        "field (`crates/omeka-api/src/errors.rs`). Every error kind and the status it answers:"
    )
    out.append("")
    out.append(table(["Error kind", "Status", "When"], error_status_rows()))
    out.append("")
    if 401 not in error_status_codes():
        out.append(
            "Romeka S answers no 401. A missing, malformed, unknown or inactive API key leaves the "
            "caller anonymous (`crates/omeka-api/src/auth.rs`), and the access check then answers "
            "403."
        )
        out.append("")
