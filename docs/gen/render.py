#!/usr/bin/env python3
"""Render `docs/api.md` from the tables in `model.py`."""

from __future__ import annotations

from markdown import code, table
from model import (
    OPERATION_NAMES,
    Doc,
    adapter_write_rows,
    error_status_codes,
    error_status_rows,
    list_parameters,
    property_row_fields,
    read_access_rows,
    request_body_rows,
)
from wire import WireItem


def render_document(doc: Doc) -> str:
    out: list[str] = [
        "# The `/api` reference",
        "",
        "Audience: a developer integrating against the HTTP API. Romeka S keeps Omeka S's `/api` "
        "surface, so a client written for Omeka S works unchanged.",
        "",
        "Generated by `docs/gen.sh` from the `omeka-api` source. Do not edit by hand: change the "
        "source, run `cd docs && ./gen.sh`, and commit both the source change and this file. "
        "`./gen.sh --check` fails when this file is stale.",
        "",
        "## What this document is generated from",
        "",
    ]
    sources_section(out)
    requests_section(out)
    responses_section(out)
    routes_section(out, doc)
    access_section(out)
    resources_section(out, doc)
    shared_section(out, doc)
    errors_section(out)
    annotations_section(out)
    embed_frame_section(out)
    derivative_retry_section(out)
    return "\n".join(out).rstrip("\n") + "\n"


